"""Copy a slim, read-only serving subset of the local master database to Supabase.

  SUPABASE_DB_URL="postgresql://postgres.<ref>:<password>@aws-0-<region>.pooler.supabase.com:5432/postgres" \
  python serving/push_to_supabase.py [--min-acres 1000] [--since 2020-01-01] [--min-score 0.6] [--dry-run]

What it copies: reference tables, sensors, fires >= min-acres since a date, their perimeters (geometry
simplified to ~10 m), their linked detections with score >= min-score, scenes, LiDAR links and raster
references. It then applies the views/functions and turns on row-level security with read-only policies
for the anon role, so the public key can read but never write. Run --dry-run first to see the size.
"""
import argparse
import os
import sys
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'ingest'))
from common import DSN  # noqa: E402

FREE_TIER_MB = 500

SUBSET = {
    # table: SELECT producing exactly the table's columns (in order) from the local master
    'lk_incident_type': 'SELECT * FROM lk_incident_type',
    'lk_cause': 'SELECT * FROM lk_cause',
    'lk_complexity': 'SELECT * FROM lk_complexity',
    'lk_fuel_group': 'SELECT * FROM lk_fuel_group',
    'us_state': 'SELECT code, usps, name, ST_SimplifyPreserveTopology(geom, 0.01) FROM us_state',
    'us_county': 'SELECT geoid, state_code, name, ST_SimplifyPreserveTopology(geom, 0.005) FROM us_county',
    'agency': 'SELECT * FROM agency',
    'sensor': 'SELECT * FROM sensor',
    'lidar_collection': 'SELECT * FROM lidar_collection',
}
EVENTS = """SELECT event_id FROM fire_event
            WHERE coalesce(reported_acres, final_acres, 0) >= %(acres)s AND discovered_at >= %(since)s"""


def copy(src, dst, table, select, params=None, cols=None):
    with src.cursor() as cs, dst.cursor() as cd:
        target = f'{table} ({", ".join(cols)})' if cols else table
        with cs.copy(f'COPY ({cs.mogrify(select, params).decode() if params else select}) TO STDOUT (FORMAT binary)') as out, \
             cd.copy(f'COPY {target} FROM STDIN (FORMAT binary)') as inp:
            for block in out:
                inp.write(block)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--min-acres', type=float, default=1000)
    ap.add_argument('--since', default='2020-01-01')
    ap.add_argument('--min-score', type=float, default=0.6)
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    p = dict(acres=a.min_acres, since=a.since, score=a.min_score)

    with psycopg.connect(DSN, options='-c TimeZone=UTC') as src:
        n_ev, n_per, n_hot = src.execute(f"""
            WITH ev AS ({EVENTS})
            SELECT (SELECT count(*) FROM ev),
                   (SELECT count(*) FROM perimeter_obs WHERE event_id IN (SELECT event_id FROM ev)),
                   (SELECT count(*) FROM hotspot_event_link WHERE event_id IN (SELECT event_id FROM ev) AND score >= %(score)s)""", p).fetchone()
        est_mb = (n_ev * 3_000 + n_per * 12_000 + n_hot * 230) / 1e6 + 40
        print(f'subset: {n_ev:,} fires, {n_per:,} perimeters, {n_hot:,} detections  ≈ {est_mb:,.0f} MB')
        if est_mb > FREE_TIER_MB:
            print(f'  over the {FREE_TIER_MB} MB free tier: raise --min-acres or --min-score, or use a paid plan')
        if a.dry_run:
            return
        url = os.environ.get('SUPABASE_DB_URL')
        if not url:
            raise SystemExit('set SUPABASE_DB_URL (Supabase dashboard → Project Settings → Database → connection string)')
        with psycopg.connect(url, options='-c TimeZone=UTC') as dst:
            for f in sorted((ROOT / 'schema').glob('*.sql')):
                dst.execute(f.read_text())
            dst.commit()
            for t, sel in SUBSET.items():
                dst.execute(f'TRUNCATE {t} CASCADE')
                copy(src, dst, t, sel)
            # identity columns: copy explicit ids
            dst.execute('ALTER TABLE fire_event ALTER COLUMN event_id SET GENERATED BY DEFAULT')
            ev_cols = [r[0] for r in src.execute("""SELECT column_name FROM information_schema.columns WHERE table_name = 'fire_event'
                                                    AND is_generated = 'NEVER' ORDER BY ordinal_position""").fetchall()]
            copy(src, dst, 'fire_event', f'SELECT {", ".join(ev_cols)} FROM fire_event WHERE event_id IN ({EVENTS})', p, ev_cols)
            dst.execute('ALTER TABLE perimeter_obs ALTER COLUMN perimeter_id SET GENERATED BY DEFAULT')
            copy(src, dst, 'perimeter_obs', f"""SELECT perimeter_id, event_id, observed_at, source, source_id, map_method, is_final, reported_acres,
                    ST_Multi(ST_CollectionExtract(ST_MakeValid(ST_SimplifyPreserveTopology(geom, 0.0001)), 3))
                    FROM perimeter_obs WHERE event_id IN ({EVENTS})""", p,
                 ['perimeter_id', 'event_id', 'observed_at', 'source', 'source_id', 'map_method', 'is_final', 'reported_acres', 'geom'])
            lo, hi = src.execute('SELECT min(acq_time)::date, max(acq_time)::date FROM hotspot').fetchone()
            dst.execute('SELECT ensure_hotspot_partitions(%s, %s)', (lo, hi))
            dst.execute('ALTER TABLE hotspot ALTER COLUMN hotspot_id SET GENERATED BY DEFAULT')
            hcols = ['hotspot_id', 'sensor_id', 'acq_time', 'latitude', 'longitude', 'scan_km', 'track_km', 'brightness_k', 'brightness2_k', 'frp_mw',
                     'confidence_raw', 'confidence_pct', 'confidence_class', 'daynight', 'fire_type', 'data_version', 'product']
            copy(src, dst, 'hotspot', f"""SELECT {', '.join('h.' + c for c in hcols)} FROM hotspot h JOIN hotspot_event_link l USING (hotspot_id, acq_time)
                    WHERE l.score >= %(score)s AND l.event_id IN ({EVENTS})""", p, hcols)
            copy(src, dst, 'hotspot_event_link', f"""SELECT * FROM hotspot_event_link WHERE score >= %(score)s AND event_id IN ({EVENTS})""", p)
            for t in ('scene', 'event_lidar', 'raster_asset'):
                cols = [r[0] for r in src.execute("""SELECT column_name FROM information_schema.columns WHERE table_name = %s
                                                     AND is_generated = 'NEVER' ORDER BY ordinal_position""", (t,)).fetchall()]
                copy(src, dst, t, f'SELECT {", ".join(cols)} FROM {t} WHERE event_id IN ({EVENTS})', p, cols)
            # read-only access for the public (anon) key
            for t in ['fire_event', 'perimeter_obs', 'hotspot', 'hotspot_event_link', 'sensor', 'scene', 'event_lidar', 'lidar_collection',
                      'raster_asset', 'weather_obs', 'canopy_sample', 'lk_cause', 'lk_incident_type', 'lk_complexity', 'lk_fuel_group',
                      'us_state', 'us_county', 'agency']:
                dst.execute(f'ALTER TABLE {t} ENABLE ROW LEVEL SECURITY')
                dst.execute(f'DROP POLICY IF EXISTS read_all ON {t}')
                dst.execute(f'CREATE POLICY read_all ON {t} FOR SELECT TO anon, authenticated USING (true)')
            dst.execute('GRANT EXECUTE ON FUNCTION event_bundle(bigint, integer), fires_near(float8, float8, float8, float8, timestamptz, timestamptz, numeric) TO anon')
            dst.commit()
            size = dst.execute('SELECT pg_size_pretty(pg_database_size(current_database()))').fetchone()[0]
            print(f'done: Supabase database is now {size}')


if __name__ == '__main__':
    main()
